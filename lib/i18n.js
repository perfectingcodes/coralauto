const DICTS = { en, es };
const LANGS = ["en", "es"];
const DEFAULT_LANG = "en";

/** Fill {{token}} from pricing VARS first, then any caller-supplied values. */
function interpolate(str, extra) {
  if (typeof str !== "string") return str;
  return str.replace(/\{\{(\w+)\}\}/g, (match, key) => {
    if (extra && Object.prototype.hasOwnProperty.call(extra, key)) return String(extra[key]);
    if (Object.prototype.hasOwnProperty.call(VARS, key)) return String(VARS[key]);
    return match;
  });
}

function normalize(lang) {
  if (!lang) return DEFAULT_LANG;
  const base = String(lang).toLowerCase().slice(0, 2);
  return LANGS.includes(base) ? base : DEFAULT_LANG;
}

/** One string, translated and interpolated. Falls back to English, then the key. */
function t(lang, key, extra) {
  const l = normalize(lang);
  const raw = DICTS[l][key] !== undefined ? DICTS[l][key] : en[key];
  if (raw === undefined) return key;
  return interpolate(raw, extra);
}

/** The whole dictionary for one language, pre-interpolated, for the client. */
function dict(lang) {
  const l = normalize(lang);
  const out = {};
  Object.keys(en).forEach((key) => {
    const raw = DICTS[l][key] !== undefined ? DICTS[l][key] : en[key];
    out[key] = interpolate(raw);
  });
  return out;
}

module.exports = { LANGS, DEFAULT_LANG, VARS, normalize, t, dict, interpolate };
